function kingSay(kind,ch){
  const t=KING_TALK[kind]&&KING_TALK[kind][ch];if(!t||!RUN||!RUN.scene)return;
  RUN.scene.npc={id:"king",name:"老國王",lines:t};
  SAVE.lore=SAVE.lore||{};const k=LORE_KEY[kind]+ch;
  if(!SAVE.lore[k]){SAVE.lore[k]=1;save();}
  glog("👑KING",`${kind} ${ch}`);
}
